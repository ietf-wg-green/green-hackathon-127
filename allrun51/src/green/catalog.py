def relationships_for_profiles(profiles: tuple[str, ...]) -> tuple[EnergyRelationship, ...]:
    return tuple(
        relationship
        for profile in profiles
        for relationship in _RELATIONSHIPS.get(profile, ())
    )


def _event(
    series: EventSeries,
    sequence: str,
    name: str,
    explanation: str,
    *,
    profiles: tuple[str, ...] = (),
    energy: tuple[tuple[str, int], ...] = (),
    power: tuple[tuple[str, int], ...] = (),
    states: tuple[tuple[str, ComponentState], ...] = (),
    metadata: tuple[tuple[str, str], ...] = (),
    cumulative: bool = False,
) -> EventSpec:
    return EventSpec(
        series,
        sequence,
        name,
        explanation,
        profiles,
        energy,
        power,
        states,
        metadata,
        cumulative,
    )


