@dataclass(frozen=True)
class EventSpec:
    series: EventSeries
    sequence: str
    name: str
    explanation: str
    relationship_profiles: tuple[str, ...]
    interval_energy_wh: tuple[tuple[str, int], ...] = ()
    instantaneous_power_w: tuple[tuple[str, int], ...] = ()
    component_states: tuple[tuple[str, ComponentState], ...] = ()
    metadata: tuple[tuple[str, str], ...] = ()
    cumulative_enabled: bool = False


@dataclass(frozen=True)
class UseCaseSpec:
    series: EventSeries
    title: str
    nickname: str | None
    events: tuple[EventSpec, ...]


def _relationship(
    profile: str,
    source: str,
    kind: RelationshipType,
    peer: str,
) -> EnergyRelationship:
    return EnergyRelationship(
        relationship_id=f"{source}:{kind.value}:{peer}",
        relationship_type=kind,
        source_energy_object_id=source,
        peer_energy_object_id=peer,
       provenance=f"allrun51:{profile}",
    )


def _pair(
    profile: str,
    source: str,
    forward: RelationshipType,
    peer: str,
    inverse: RelationshipType,
) -> tuple[EnergyRelationship, EnergyRelationship]:
    return (
        _relationship(profile, source, forward, peer),
        _relationship(profile, peer, inverse, source),
    )


